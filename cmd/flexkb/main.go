// loadComposeChains resolves the LayoutSpec's Compose names against
// the data root. Missing chains are skipped with a warning (so a
// half-authored layout doesn't crash the build); each successfully
// loaded chain is returned in the order listed.
func loadComposeChains(root model.DataRoot, v model.LayoutSpec) ([]model.ComposeChain, error) {
	if len(v.Compose) == 0 {
		return nil, nil
	}
	chains := make([]model.ComposeChain, 0, len(v.Compose))
	for _, name := range v.Compose {
		c, err := root.Compose(name)
		if err != nil {
			fmt.Fprintf(os.Stderr, "warn: compose chain %q referenced by %q not found: %v\n", name, v.Name, err)
			continue
		}
		chains = append(chains, c)
	}
	return chains, nil
}

// writeVariantCompose emits the X-Compose snippet for one variant's
// listed chains. Returns false if the variant has no chains (caller
// can skip the file write).
func writeVariantCompose(w io.Writer, root model.DataRoot, lf model.LayoutFile, v model.LayoutSpec) (bool, error) {
	chains, err := loadComposeChains(root, v)
	if err != nil {
		return false, err
	}
	if len(chains) == 0 {
		return false, nil
	}
	hdr := fmt.Sprintf("Generated by flexkb for %s(%s). Source: data/compose/*.yaml.\nMerge into ~/.XCompose to enable these sequences for X11/Wayland clients\nthat read the system Compose configuration (libX11, libxkbcommon).", lf.File, v.Name)
	return true, composewriter.WriteFile(w, composewriter.Options{HeaderComment: hdr}, chains)
}

const defaultXKBRoot = "/usr/share/X11/xkb"

func main() {
	if len(os.Args) < 2 {
		usage()
		os.Exit(2)
	}
	cmd := os.Args[1]
	args := os.Args[2:]

	switch cmd {
	case "compose":
		runCompose(args)
	case "generate":
		runGenerate(args)
	case "build":
		runBuild(args)
	case "verify":
		runVerify(args)
	case "list":
		runList(args)
	case "paths":
		runPaths(args)
	case "activate":
		runActivate(args)
	case "info":
		runInfo(args)
	case "validate":
		runValidate(args)
	case "doctor":
		runDoctor(args)
	case "migrate-suggest":
		runMigrateSuggest(args)
	case "dropin-check":
		runDropinCheck(args)
	case "serve":
		runServe(args)
	case "gui":
		runGui(args)
	case "-h", "--help", "help":
		usage()
	default:
		fmt.Fprintf(os.Stderr, "unknown command %q\n", cmd)
		usage()
		os.Exit(2)
	}
}

